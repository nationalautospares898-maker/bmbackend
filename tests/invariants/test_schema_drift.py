"""Schema drift: ORM metadata and the migrated database must agree.

What this file is for
---------------------

The 30 October 2026 audit ran `alembic check` and found **twelve proposed removals** —
one foreign key and eleven indexes. Nothing was broken at the time: the migrations create
all twelve, and the upgrade/downgrade roundtrip passed. The danger was entirely in the
future. `alembic revision --autogenerate` compares the database against ORM *metadata*,
and metadata did not know those twelve objects existed, so the next autogenerated
revision would have contained `DROP INDEX ix_products__search_trgm` and friends — the
indexes NFR-PERF-001 depends on, and the tenancy indexes migration `0017` added as
defence in depth against a cross-tenant query.

That is a failure mode with no symptom until it is irreversible, which is exactly the
kind this suite exists to catch. Two complementary assertions:

1. **`test_orm_metadata_matches_the_database`** is `alembic check` as a test. It fails on
   *any* difference in either direction, so a future hand-written migration that is not
   reflected in the models, or a model change with no migration, fails here rather than
   in a surprising autogenerated diff later.
2. **`test_protected_objects_exist` / `test_protected_objects_are_in_orm_metadata`** pin
   the twelve objects by name, in the database and in metadata respectively. The first
   would catch a migration that stopped creating one; the second would catch someone
   "fixing" a drift report by deleting the metadata declaration instead of the object.

Both are needed. The first alone could be satisfied by removing an object from the
database *and* from metadata; the named list is what makes that a failure.

No exclusion list
-----------------

The audit left open the option of a "narrow, controlled schema-diff configuration"
listing intentional migration-managed exceptions. None was needed. All twelve objects
turned out to be expressible in ORM metadata — the operator classes through
`postgresql_ops`, the partial predicates through `postgresql_where`, the deferred
foreign key through a named `ForeignKey(..., use_alter=True)` — so the diff is clean with
zero exemptions, and there is no list to quietly grow.
"""

from __future__ import annotations

import pytest
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from sqlalchemy import Engine, text
from sqlalchemy.orm import Session

from bm.infra.db import models as _models  # noqa: F401  (registers every mapper)
from bm.infra.db.base import Base

pytestmark = pytest.mark.db

#: The twelve objects the audit found missing from ORM metadata, as
#: `(object name, table)`. Named individually and deliberately: a count would pass while
#: the wrong eleven existed.
#:
#: The five `products`/`product_aliases` entries are the search indexes NFR-PERF-001
#: depends on (migration `0018`). The five `__business` entries are the child-table
#: tenancy indexes from `0017`, which exist so a query that forgets the parent join
#: cannot return another business's rows. `ix_import_jobs__ordinal` is what makes
#: `0020`'s "newest first" a guarantee rather than a hope.
PROTECTED_INDEXES: tuple[tuple[str, str], ...] = (
    ("ix_products__sku_prefix", "products"),
    ("ix_products__name_prefix", "products"),
    ("ix_products__search_trgm", "products"),
    ("ix_products__name_trgm", "products"),
    ("ix_product_aliases__prefix", "product_aliases"),
    ("ix_draft_bill_items__business", "draft_bill_items"),
    ("ix_purchase_items__business", "purchase_items"),
    ("ix_sales_return_items__business", "sales_return_items"),
    ("ix_stock_count_items__business", "stock_count_items"),
    ("ix_import_rows__business", "import_rows"),
    ("ix_import_jobs__ordinal", "import_jobs"),
)

PROTECTED_FOREIGN_KEYS: tuple[tuple[str, str], ...] = (("fk_counters__invoice_series", "counters"),)

#: The index definitions whose *access method or operator class* carries the behaviour,
#: not just the column list. A btree index on `normalized_sku` without
#: `text_pattern_ops` cannot serve `LIKE 'abc%'` under a non-C collation at all — the
#: planner ignores it — so an index that exists by name but lost its operator class is a
#: silent reversion to a sequential scan. That is the precise defect migration `0018`
#: was written to repair, and asserting the name alone would not have caught it.
INDEX_DEFINITION_FRAGMENTS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("ix_products__sku_prefix", ("btree", "normalized_sku text_pattern_ops", "IS NOT NULL")),
    ("ix_products__name_prefix", ("btree", "normalized_name text_pattern_ops")),
    ("ix_products__search_trgm", ("gin", "search_text gin_trgm_ops")),
    ("ix_products__name_trgm", ("gin", "normalized_name gin_trgm_ops")),
    ("ix_product_aliases__prefix", ("btree", "normalized_alias text_pattern_ops")),
)


def _diff(engine: Engine) -> list:
    """The autogenerate diff, exactly as `alembic check` computes it.

    `compare_type` and `compare_server_default` mirror `migrations/env.py`, so this test
    and the CLI cannot disagree about what counts as drift.
    """
    with engine.connect() as connection:
        context = MigrationContext.configure(
            connection,
            opts={"compare_type": True, "compare_server_default": True},
        )
        return list(compare_metadata(context, Base.metadata))


def test_orm_metadata_matches_the_database(migration_engine: Engine, schema_at_head: None) -> None:
    """`alembic check`, as a test that runs in the ordinary suite.

    A difference here is not necessarily a bug in the database — more often it is a
    model that has not been told about an object a migration creates. Either way it must
    be resolved deliberately, because the thing it silently licenses is an autogenerated
    `DROP`.
    """
    differences = _diff(migration_engine)
    assert not differences, (
        "ORM metadata and the migrated schema disagree. Resolve this by declaring the "
        "object in the models (see the note on the search indexes in "
        "`bm/infra/db/models/catalog.py`) — not by accepting an autogenerated DROP.\n"
        + "\n".join(f"  - {d}" for d in differences)
    )


@pytest.mark.parametrize(("name", "table"), PROTECTED_INDEXES)
def test_protected_indexes_exist_in_the_database(
    migration_session: Session, schema_at_head: None, name: str, table: str
) -> None:
    row = migration_session.execute(
        text("SELECT tablename FROM pg_indexes WHERE indexname = :name"), {"name": name}
    ).first()
    assert row is not None, f"{name} is missing from the database"
    assert row[0] == table, f"{name} is on {row[0]}, expected {table}"


@pytest.mark.parametrize(("name", "table"), PROTECTED_FOREIGN_KEYS)
def test_protected_foreign_keys_exist_in_the_database(
    migration_session: Session, schema_at_head: None, name: str, table: str
) -> None:
    """`fk_counters__invoice_series` in particular.

    Migration `0010` adds it inside an `if _app_role_exists():` guard, so on a cluster
    without the `bm_app` role it was silently never created. Migration `0021` repairs
    that unconditionally; this is the assertion that says so.
    """
    row = migration_session.execute(
        text(
            "SELECT c.conrelid::regclass::text, c.confdeltype"
            "  FROM pg_constraint c WHERE c.conname = :name AND c.contype = 'f'"
        ),
        {"name": name},
    ).first()
    assert row is not None, f"{name} is missing from the database"
    assert row[0] == table
    # 'n' is SET NULL — a counter whose optional series is deleted loses the pointer
    # rather than blocking the delete.
    assert row[1] == "n", f"{name} should be ON DELETE SET NULL, found {row[1]!r}"


@pytest.mark.parametrize(("name", "table"), PROTECTED_INDEXES + PROTECTED_FOREIGN_KEYS)
def test_protected_objects_are_declared_in_orm_metadata(name: str, table: str) -> None:
    """The other half of the guard.

    Without this, a future drift report could be "fixed" by deleting the declaration —
    or the object — rather than by reconciling the two, and the diff would go green
    while the index went away.
    """
    declared: set[str] = set()
    for mapped_table in Base.metadata.tables.values():
        declared.update(index.name for index in mapped_table.indexes if index.name)
        declared.update(
            constraint.name
            for constraint in mapped_table.constraints
            if constraint.name and type(constraint).__name__ == "ForeignKeyConstraint"
        )
    assert name in declared, (
        f"{name} exists in the database but is not declared in ORM metadata; "
        "autogenerate would propose dropping it"
    )


@pytest.mark.parametrize(("name", "fragments"), INDEX_DEFINITION_FRAGMENTS)
def test_search_indexes_keep_their_operator_classes(
    migration_session: Session, schema_at_head: None, name: str, fragments: tuple[str, ...]
) -> None:
    """An index that exists by name but lost `text_pattern_ops` or `gin_trgm_ops` is a
    sequential scan wearing an index's name."""
    definition = migration_session.execute(
        text("SELECT indexdef FROM pg_indexes WHERE indexname = :name"), {"name": name}
    ).scalar_one_or_none()
    assert definition is not None, f"{name} is missing from the database"
    for fragment in fragments:
        assert fragment in definition, f"{name} no longer contains {fragment!r}:\n  {definition}"


def test_the_protected_list_covers_every_object_the_audit_found() -> None:
    """A guard on the guard: the audit counted twelve, so this list holds twelve."""
    assert len(PROTECTED_INDEXES) + len(PROTECTED_FOREIGN_KEYS) == 12
